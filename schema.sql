-- =============================================================
-- EXPENSES
-- =============================================================
CREATE TABLE expenses (
    expense_id      INT             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INT             NOT NULL
                    REFERENCES users(employee_id) ON DELETE RESTRICT,
    project_id      INT             NOT NULL
                    REFERENCES projects(project_id) ON DELETE RESTRICT,
    organization_id INT             NOT NULL
                    REFERENCES organizations(organization_id) ON DELETE RESTRICT,
    expense_type_id INT             NOT NULL
                    REFERENCES expense_types(expense_type_id) ON DELETE RESTRICT,
    amount          DECIMAL(15, 2)  NOT NULL CHECK (amount > 0),
    status          VARCHAR(20)     NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'approved', 'rejected', 'reimbursed')),
    rejection_reason VARCHAR(255),
    expense_date    DATE            NOT NULL,
    submission_date TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_rejection_reason
        CHECK (status != 'rejected' OR rejection_reason IS NOT NULL)
);

CREATE TRIGGER set_updated_at_expenses
    BEFORE UPDATE ON expenses
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

CREATE TRIGGER validate_expense_org
    BEFORE INSERT OR UPDATE ON expenses
    FOR EACH ROW EXECUTE FUNCTION validate_expense_org_consistency();

CREATE INDEX idx_expenses_employee ON expenses(employee_id);
CREATE INDEX idx_expenses_project  ON expenses(project_id);
CREATE INDEX idx_expenses_org      ON expenses(organization_id);
CREATE INDEX idx_expenses_status   ON expenses(status);
CREATE INDEX idx_expenses_type     ON expenses(expense_type_id);

