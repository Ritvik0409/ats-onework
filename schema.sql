CREATE TABLE users (
    employee_id     INT             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)    NOT NULL,
    email           VARCHAR(254)    NOT NULL UNIQUE,
    password_hash   TEXT            NOT NULL,
    account_status  VARCHAR(20)     NOT NULL DEFAULT 'active'
                    CHECK (account_status IN ('active', 'suspended', 'locked', 'inactive')),
    is_superuser    BOOLEAN         NOT NULL DEFAULT FALSE,
    last_login_at   TIMESTAMP,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER set_updated_at_users
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

-- =============================================================
-- EMPLOYEE_STATUS
-- Temporal status log with strict single-active record constraint
-- =============================================================
CREATE TABLE employee_status (
    status_id       INT             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INT             NOT NULL
                    REFERENCES users(employee_id) ON DELETE RESTRICT,
    status          VARCHAR(20)     NOT NULL
                    CHECK (status IN ('active', 'inactive', 'suspended', 'on_leave')),
    started_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at        TIMESTAMP,
    updated_by      INT
                    REFERENCES users(employee_id) ON DELETE SET NULL,
    CONSTRAINT chk_status_dates CHECK (ended_at IS NULL OR ended_at > started_at)
);

CREATE INDEX idx_employee_status_employee ON employee_status(employee_id);
CREATE UNIQUE INDEX idx_employee_status_single_active 
    ON employee_status(employee_id) WHERE ended_at IS NULL;

