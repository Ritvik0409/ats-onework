    new_values      JSONB,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_logs_actor      ON audit_logs(actor_id);
CREATE INDEX idx_audit_logs_table      ON audit_logs(table_name);
CREATE INDEX idx_audit_logs_created_at ON audit_logs(created_at);
CREATE INDEX idx_audit_logs_old_values ON audit_logs USING GIN (old_values);
CREATE INDEX idx_audit_logs_new_values ON audit_logs USING GIN (new_values);

-- =============================================================
-- AUTHENTICATION_TOKENS
-- =============================================================
CREATE TABLE authentication_tokens (
    token_id        INT             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INT             NOT NULL
                    REFERENCES users(employee_id) ON DELETE CASCADE,
    token_hash      TEXT            NOT NULL,
    purpose         VARCHAR(50)     NOT NULL
                    CHECK (purpose IN ('login', 'reset_password', 'refresh', 'verify_email')),
    expires_at      TIMESTAMP       NOT NULL,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- High-performance HASH index for token equality checks
CREATE INDEX idx_auth_tokens_hash             ON authentication_tokens USING HASH (token_hash);
CREATE INDEX idx_auth_tokens_expires_at      ON authentication_tokens(expires_at);
CREATE INDEX idx_auth_tokens_employee_purpose ON authentication_tokens(employee_id, purpose);

