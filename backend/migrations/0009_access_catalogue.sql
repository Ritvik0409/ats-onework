-- =============================================================
-- 0009 — ACCESS CATALOGUE (the platform's standard access model)
-- =============================================================
-- The role tables existed but were never populated and never read, so
-- the only distinction the API could make was "is this person an
-- admin". The UI had screens for director, finance and HR roles that
-- no account could ever reach, and the role management API created
-- roles that granted nothing.
--
-- This migration adds the one thing the existing schema cannot hold:
-- a *platform-level* definition of what access exists.
--
--   permissions        per organization -- unchanged. A capability
--                      belongs to an organization, and each organization
--                      keeps its own copy of it.
--   roles              per organization -- unchanged.
--   access_catalog     the standard set the platform ships with:
--                        kind = 'permission'  a capability and what it means
--                        kind = 'role'        a standard role and the
--                                           capabilities it grants
--
-- A new organization is seeded from the catalogue: it gets a copy of
-- every standard capability, and the standard roles with their grants.
-- After that, an organization is free to change its own roles and
-- grants -- which is what the administration API is for.
--
-- The install functions are idempotent and never undo work: installing
-- a capability only adds a row that does not exist yet, and installing
-- a role only creates the role (with the catalogue's grants) when it
-- is missing. An organization that has already configured a role keeps
-- its own grants.

-- -- 1. The catalogue ----------------------------------------------------

CREATE TABLE access_catalog (
    catalog_id  INT             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(20)     NOT NULL
                CHECK (kind IN ('permission', 'role')),
    name        VARCHAR(100)    NOT NULL,
    description TEXT,
    -- For kind = 'role': the names of the capabilities it grants.
    grants      TEXT[]          NOT NULL DEFAULT '{}',
    created_at  TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (kind, name)
);

CREATE TRIGGER set_updated_at_access_catalog
    BEFORE UPDATE ON access_catalog
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

