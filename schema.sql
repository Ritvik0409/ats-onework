-- =============================================================
-- SHARED TRIGGER FUNCTION
-- =============================================================
CREATE OR REPLACE FUNCTION trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =============================================================
-- CROSS-TENANT VALIDATION TRIGGER
-- Validates that project, expense_type, and submitting employee
-- all belong to the exact same organization_id as the expense.
-- =============================================================
CREATE OR REPLACE FUNCTION validate_expense_org_consistency()
RETURNS TRIGGER AS $$
DECLARE
    v_project_org_id      INT;
    v_expense_type_org_id INT;
BEGIN
    -- 1. Validate Employee Membership
    IF NOT EXISTS (
        SELECT 1 FROM memberships 
        WHERE employee_id = NEW.employee_id 
          AND organization_id = NEW.organization_id
    ) THEN
        RAISE EXCEPTION 
            'Cross-tenant violation: employee % is not an active member of org %', 
            NEW.employee_id, NEW.organization_id;
    END IF;

    -- 2. Validate Project Organization
    SELECT b.organization_id INTO v_project_org_id
    FROM projects p
    JOIN budgets b ON b.budget_id = p.budget_id
    WHERE p.project_id = NEW.project_id;

    IF v_project_org_id IS DISTINCT FROM NEW.organization_id THEN
        RAISE EXCEPTION
            'Cross-tenant violation: project % belongs to org % but expense is for org %',
            NEW.project_id, v_project_org_id, NEW.organization_id;
    END IF;

    -- 3. Validate Expense Type Organization
    SELECT organization_id INTO v_expense_type_org_id
    FROM expense_types
    WHERE expense_type_id = NEW.expense_type_id;

    IF v_expense_type_org_id IS DISTINCT FROM NEW.organization_id THEN
        RAISE EXCEPTION
            'Cross-tenant violation: expense_type % belongs to org % but expense is for org %',
            NEW.expense_type_id, v_expense_type_org_id, NEW.organization_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

