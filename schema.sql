-- =============================================================
-- REIMBURSEMENTS
-- =============================================================
CREATE TABLE reimbursements (
    reimbursement_id INT            GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id      INT             NOT NULL UNIQUE
                    REFERENCES expenses(expense_id) ON DELETE RESTRICT,
    employee_id     INT             NOT NULL
                    REFERENCES users(employee_id) ON DELETE RESTRICT,
    organization_id INT             NOT NULL
                    REFERENCES organizations(organization_id) ON DELETE RESTRICT,
    total_amount    DECIMAL(15, 2)  NOT NULL CHECK (total_amount > 0),
    payment_reference VARCHAR(100),
    status          VARCHAR(20)     NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'processing', 'paid', 'failed')),
    paid_at         TIMESTAMP,
    created_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_paid_atre
        CHECK (status != 'paid' OR paid_at IS NOT NULL)
);

CREATE TRIGGER set_updated_at_reimbursements
    BEFORE UPDATE ON reimbursements
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

