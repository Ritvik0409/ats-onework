-- =============================================================
-- 0002 — PROJECT ACCESS REQUESTS (additive; never edit 0001, §18)
-- =============================================================
-- Employees ask an admin for project membership. Grants materialize as
-- rows in the pre-existing project_members join table (0001), so this
-- migration adds only the request lifecycle:
--   pending  -> approved | rejected (decision is terminal; re-request
--                                  after a rejection creates a NEW row)
--
-- Tenant scoping: organization_id is denormalized from the project's
-- budget (§8) so list/decision queries can filter without joins.

CREATE TABLE project_access_requests (
    access_request_id INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        INT          NOT NULL
                      REFERENCES projects(project_id) ON DELETE CASCADE,
    employee_id       INT          NOT NULL
                      REFERENCES users(employee_id) ON DELETE CASCADE,
    organization_id   INT          NOT NULL
                      REFERENCES organizations(organization_id) ON DELETE CASCADE,
    status            VARCHAR(20)  NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'approved', 'rejected')),
    decided_by        INT          REFERENCES users(employee_id) ON DELETE SET NULL,
    decision_comment  VARCHAR(255),
    requested_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at        TIMESTAMP,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_par_decision
        CHECK (
            (status = 'pending' AND decided_at IS NULL AND decided_by IS NULL)
            OR (status IN ('approved', 'rejected') AND decided_at IS NOT NULL)
        )
);

CREATE TRIGGER set_updated_at_project_access_requests
    BEFORE UPDATE ON project_access_requests
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

CREATE INDEX idx_par_org      ON project_access_requests(organization_id);
CREATE INDEX idx_par_project  ON project_access_requests(project_id);
CREATE INDEX idx_par_employee ON project_access_requests(employee_id);
CREATE INDEX idx_par_status   ON project_access_requests(status);

-- One pending request per employee per project at a time. Re-applying
-- after a decision inserts a fresh row (partial unique, not a hard
-- (project_id, employee_id) unique).
CREATE UNIQUE INDEX uq_par_pending
    ON project_access_requests (project_id, employee_id)
    WHERE status = 'pending';
