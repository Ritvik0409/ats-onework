-- -- 4. Install functions -------------------------------------------------

CREATE OR REPLACE FUNCTION ats_install_permissions(target_org_id INT) RETURNS INT AS $$
DECLARE
    inserted INT := 0;
BEGIN
    INSERT INTO permissions (api_name, organization_id, is_global, description)
    SELECT c.name, target_org_id, TRUE, c.description
      FROM access_catalog c
     WHERE c.kind = 'permission'
       AND NOT EXISTS (
           SELECT 1 FROM permissions p
            WHERE p.api_name = c.name
              AND p.organization_id = target_org_id
       );
    GET DIAGNOSTICS inserted = ROW_COUNT;
    RETURN inserted;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION ats_install_roles(target_org_id INT) RETURNS INT AS $$
DECLARE
    created INT := 0;
    granted INT := 0;
    role_row RECORD;
BEGIN
    FOR role_row IN
        SELECT name, description, grants FROM access_catalog
         WHERE kind = 'role' ORDER BY name
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM roles
             WHERE name = role_row.name AND organization_id = target_org_id
        ) THEN
            INSERT INTO roles (name, organization_id, description)
            VALUES (role_row.name, target_org_id, role_row.description);
            created := created + 1;
        END IF;

        -- A role that grants nothing has never been configured, so it
        -- takes the catalogue's grants. A role that grants something
        -- keeps exactly what the organization has chosen -- installing
        -- must never undo an administrator's work.
        IF NOT EXISTS (
            SELECT 1 FROM role_permissions rp
              JOIN roles r ON r.role_id = rp.role_id
             WHERE r.name = role_row.name
               AND r.organization_id = target_org_id
        ) THEN
            -- The organization's own copy of each capability is the row
            -- that gets linked, so a role can only ever grant a
            -- capability its own organization holds.
            INSERT INTO role_permissions (role_id, organization_id, permission_id)
            SELECT r.role_id, target_org_id, p.permission_id
              FROM roles r
              JOIN permissions p ON p.organization_id = target_org_id
              JOIN access_catalog c
                ON c.kind = 'permission' AND c.name = p.api_name
             WHERE r.name = role_row.name
               AND r.organization_id = target_org_id
               AND c.name = ANY (role_row.grants)
            ON CONFLICT DO NOTHING;
            GET DIAGNOSTICS granted = ROW_COUNT;
        END IF;
    END LOOP;
    RETURN created;
END;
$$ LANGUAGE plpgsql;

-- -- 5. Backfill the organizations that already exist ---------------------

DO $$
DECLARE
    org_row RECORD;
BEGIN
    FOR org_row IN SELECT organization_id FROM organizations ORDER BY organization_id LOOP
        PERFORM ats_install_permissions(org_row.organization_id);
        PERFORM ats_install_roles(org_row.organization_id);
    END LOOP;
END $$;

-- -- 6. A grant must reference a capability of the same organization -----
--
-- The per-organization copy of the catalogue makes it possible to point
-- a role at another organization's permission by id. These constraints
-- make that impossible.

ALTER TABLE permissions
    ADD CONSTRAINT uq_permissions_org_id UNIQUE (permission_id, organization_id);

ALTER TABLE role_permissions
    ADD CONSTRAINT fk_role_permissions_permission_org
    FOREIGN KEY (permission_id, organization_id)
    REFERENCES permissions (permission_id, organization_id);

ALTER TABLE user_permissions
    ADD CONSTRAINT fk_user_permissions_permission_org
    FOREIGN KEY (permission_id, organization_id)
    REFERENCES permissions (permission_id, organization_id);
